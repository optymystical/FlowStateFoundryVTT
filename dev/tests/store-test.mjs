// The world data store: system defaults, a world's edits layered on top (in place, where the engine reads), resets, safety, and what's derived.
await import("../../module/store-catalog.mjs");
const S = await import("../../module/store.mjs");
const martial = await import("../../module/martial.mjs");
const magic = await import("../../module/magic.mjs");
const R = await import("../../module/mental-rules.mjs");
const skills = await import("../../module/skills.mjs");
const spells = await import("../../module/spells.mjs");
const { TREES } = await import("../../module/trees.mjs");
const { STATS } = await import("../../module/rules.mjs");
let fails = 0; const ok = (c, m) => { console.log(`  ${c ? "PASS" : "FAIL"} ${m}`); if (!c) fails++; };
const same = (a, b) => JSON.stringify(a, (k, v) => (v === Infinity ? "∞" : v)) === JSON.stringify(b, (k, v) => (v === Infinity ? "∞" : v));

console.log("== The system's data, unchanged");
const before = { mats: S.clone(martial.WEAPON_MATERIALS), trees: S.clone(TREES), armor: S.clone(martial.ARMOR_WEIGHTS) };
const wonders0 = R.WONDERS.length, catalog0 = spells.CATALOG.length;
let res = S.applyWorldData({});
ok(!res.problems.length && same(martial.WEAPON_MATERIALS, before.mats) && same(TREES, before.trees), "No world data: every table is exactly the system's");
ok(martial.ARMOR_WEIGHTS.titanic.stealthDis === Infinity, "…values JSON can't hold (Titanic armor's auto-fail stealth) survive");
ok(R.WONDERS.length === wonders0 && spells.CATALOG.length === catalog0 && wonders0 === 20, `The Wonders (${wonders0}) and the spell catalog (${catalog0}) are rebuilt the same`);
ok(S.COLLECTIONS.size >= 30, `${S.COLLECTIONS.size} tables are in the store`);

console.log("== Edits layer over the system's values, in place");
const ironRef = martial.WEAPON_MATERIALS;
let data = S.withEntry({}, "weaponMaterials", "iron", { weights: { heavy: { dur: 70 } } });
ok(same(data.collections.weaponMaterials.entries.iron, { weights: { heavy: { dur: 70 } } }), "An edit stores only the field that changed");
S.applyWorldData(data);
ok(martial.WEAPON_MATERIALS === ironRef && martial.WEAPON_MATERIALS.iron.weights.heavy.dur === 70 && martial.WEAPON_MATERIALS.iron.weights.heavy.limit === 12 && martial.WEAPON_MATERIALS.iron.label === "Iron", "The table the engine reads now has Durability 70; Limit and name still the system's");
ok(martial.weaponProfile({ type: "bladed", weight: "heavy", material: "iron", grade: 1 }, { str: 30 }).durability === 70 * 2, "…and a Heavy Bladed iron weapon (Broad) gets 140 Durability from it");
data = S.withEntry(data, "weaponMaterials", "duskSteel", { label: "Dusk Steel", rarity: "rare", weights: { light: { dur: 50, limit: 10 } }, effect: "Homebrew.", mods: { stacks: 1 } });
S.applyWorldData(data);
const dusk = martial.weaponProfile({ type: "bladed", weight: "light", material: "duskSteel", grade: 2 }, { dex: 30 });
ok(dusk.valid && dusk.durability === 100 && dusk.limit === 20, "A new material works like any other (Light Bladed, Grade 2: 100 Durability, 20 Limit)");
ok(S.entries("weaponMaterials", data).find(e => e.key === "duskSteel")?.custom && S.entries("weaponMaterials", data).find(e => e.key === "iron")?.edited, "The store knows which entries the world added and which it edited");
S.applyWorldData({});
ok(martial.WEAPON_MATERIALS.iron.weights.heavy.dur === 60 && !martial.WEAPON_MATERIALS.duskSteel, "Clearing the world data puts the system's values back and drops what it added");
data = S.withEntry({}, "fociTypes", "chime", { deckTR: [3, 5] });
S.applyWorldData(data);
ok(same(magic.FOCI_TYPES.chime.deckTR, [3, 5]) && magic.FOCI_TYPES.chime.draw === 7, "A plain list is replaced whole");
S.applyWorldData(S.withEntry({}, "rarities", "rare", "Exotic"));
ok(magic.AFFIX_RARITIES.rare === "Exotic" && martial.RARITIES.rare === "Exotic", "Rarities are one table: renaming one reads the same for Affixes and everything else");

console.log("== What a world can't do");
res = S.applyWorldData(S.withEntry({}, "stats", "luck", { label: "Luck", abbr: "Luk", group: "Body" }));
ok(!STATS.luck && /can't be added/.test(res.problems.join()), "No new stats: the engine works with the nine by name");
res = S.applyWorldData(S.withEntry({}, "weaponMaterials", "half", { label: "Half" }));
ok(!martial.WEAPON_MATERIALS.half && /missing rarity, weights/.test(res.problems.join()), "A new entry without its required fields is left out");
res = S.applyWorldData(JSON.parse('{"collections":{"weaponMaterials":{"entries":{"iron":{"__proto__":{"polluted":1},"label":"Iron!"},"__proto__":{"x":1}}}}}'));
ok(({}).polluted === undefined && martial.WEAPON_MATERIALS.iron.label === "Iron!" && Object.getPrototypeOf(martial.WEAPON_MATERIALS.iron) === Object.prototype, "A crafted file can't reach the object prototype (the rest of it still applies)");
res = S.applyWorldData({ collections: { nope: { entries: { a: 1 } } } });
ok(/Unknown collection/.test(res.problems.join()), "Unknown tables are reported and left out");
res = S.sanitizeWorldData({ version: 99, collections: {} });
ok(/newer version/.test(res.problems.join()), "Data from a newer format is flagged");
S.applyWorldData({});

console.log("== Skill trees: edits merge entry by entry, and the Wonders and spells follow");
const life = "mental-life-dream";
data = S.withEntry({}, "skillTrees", life, { tiers: [{ tier: 1, entries: [{ name: "Bloom", text: "HOMEBREW bloom. Enhanced: more." }] }] });
S.applyWorldData(data);
const bloom = R.modeById(`${life}:bloom`);
ok(bloom?.base === "HOMEBREW bloom." && bloom.enhanced === "more.", "Editing Bloom's text: the Wonder's Mode reads the new text");
ok(R.wonderById(life).tenet?.name === "Verdant Soul" && skills.treeById(life).tiers.length === 5, "…the rest of the tier (Verdant Soul) and the other tiers are still the system's");
data = S.withEntry(data, "skillTrees", life, { tiers: [{ tier: 2, entries: [{ name: "Pollinate", _delete: true }] }] });
S.applyWorldData(data);
ok(!R.wonderById(life).abilities.some(a => a.name === "Pollinate") && R.modeById(`${life}:bloom`)?.base === "HOMEBREW bloom.", "An entry can be dropped (Pollinate), and the earlier edit stays");
const cut = spells.spellById("magic-slashing:cut");
const cutText = skills.treeById("magic-slashing").tiers[0].entries[0].text;
S.applyWorldData(S.withEntry({}, "skillTrees", "magic-slashing", { tiers: [{ tier: 1, entries: [{ name: "Cut", text: cutText.replace(/^(\d+)/, "3") }] }] }));
ok(cut && spells.CATALOG.length === catalog0 && spells.spellById("magic-slashing:cut"), "The spell catalog is rebuilt from the edited tree");
data = S.withEntry({}, "skillTrees", "martial-homebrew", { name: "Homebrew Weapons", archetype: "martial", requires: 1, tiers: [{ tier: 1, free: false, summary: "A test tier.", entries: [{ name: "Thing", text: "Does a thing." }] }] });
S.applyWorldData(data);
ok(skills.treeById("martial-homebrew")?.name === "Homebrew Weapons" && skills.treesFor("martial").some(t => t.id === "martial-homebrew"), "A new tree shows up with its Archetype's trees");
S.applyWorldData({});
ok(!skills.treeById("martial-homebrew") && R.WONDERS.length === wonders0 && R.wonderById(life).abilities.some(a => a.name === "Pollinate"), "…and clearing puts every tree back");

console.log("== Icon Forms, lists, and hiding");
S.applyWorldData(S.withEntry({}, "iconForms", "bulwark", { name: "Bulwark", align: "dream", rarity: "common", kind: "shield", ward: "Homebrew.", enhance: "", amount: 10, enhanced: 20, ap: 1 }));
ok(R.FORM_KEYS.includes("bulwark") && R.iconProfile({ form: "bulwark", grade: 1 }, { will: 10 }).valid, "A new Icon Form joins the Forms and has a profile");
S.applyWorldData(S.withEntry({}, "animationMaterials", "Moonglass", { category: "hard", rarity: "rare" }));
const { animMaterial } = await import("../../module/conjure-rules.mjs");
ok(animMaterial("Moonglass")?.category === "hard" && animMaterial("Water")?.category === "liquid", "A list table (Animation materials) takes a new entry by name");
data = S.withHidden({}, "weaponMaterials", "glass");
S.applyWorldData(data);
ok(martial.WEAPON_MATERIALS.glass?.hidden === true && martial.weaponProfile({ type: "bladed", weight: "light", material: "glass", grade: 1 }, { dex: 10 }).valid, "Hiding marks an entry but keeps it working for items that already use it");
ok(S.entries("weaponMaterials", data).find(e => e.key === "glass").hidden, "…and the store reports it hidden");
data = S.withHidden(data, "weaponMaterials", "glass", false);
ok(!data.collections.weaponMaterials, "Showing it again leaves nothing behind");
data = S.withoutEntry(S.withEntry({}, "weaponMaterials", "iron", { label: "X" }), "weaponMaterials", "iron");
ok(!data.collections.weaponMaterials, "Undoing an edit leaves nothing behind");

console.log("== Importing on top of a world's own data");
const mine = S.withEntry(S.withEntry({}, "weaponMaterials", "iron", { label: "Mine" }), "weaponMaterials", "stone", { label: "Rock" });
const theirs = S.withHidden(S.withEntry({}, "weaponMaterials", "iron", { effect: "Theirs." }), "affixes", "ruby");
const both = S.layerWorldData(mine, theirs);
S.applyWorldData(both);
ok(martial.WEAPON_MATERIALS.iron.label === "Mine" && martial.WEAPON_MATERIALS.iron.effect === "Theirs." && martial.WEAPON_MATERIALS.stone.label === "Rock" && magic.AFFIXES.ruby.hidden, "Their changes layer over mine field by field, and mine they don't touch stay");
ok(same(S.sanitizeWorldData(JSON.parse(JSON.stringify(both))).data, both), "World data survives a trip through a file unchanged");
S.applyWorldData({});
ok(same(martial.WEAPON_MATERIALS, before.mats) && same(TREES, before.trees) && same(martial.ARMOR_WEIGHTS, before.armor), "After it all, clearing leaves the system's data exactly as it started");

console.log(fails ? `\n${fails} FAILED` : "\nAll store checks passed");
if (fails) process.exit(1);
