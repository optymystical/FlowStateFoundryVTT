// Builds the system's compendium packs from the item catalog (npm run packs). Every document's _id comes from its catalog key, so it never changes
// between builds or system versions: an Adventure (or a roll table, a journal link) can point at
// Compendium.flowstate.<pack>.Item.<id> and keep working. The JSON sources are written to dev/packs/<pack>/ (kept in git, readable), then compiled
// into packs/<pack>/ (LevelDB, what Foundry loads). Foundry must not have the world open while this runs over packs it already loaded.
import { mkdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { compilePack } from "@foundryvtt/foundryvtt-cli";
import { stableId } from "./build-packs-ids.mjs";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "../..");
const C = await import("../../module/catalog.mjs");
const { POTIONS, TOKEN_KEY, potionKey } = await import("../../module/consumables-rules.mjs");

const STATS = { coreVersion: "14", systemId: "flowstate", systemVersion: null, createdTime: null, modifiedTime: null, lastModifiedBy: null };

function itemDoc(key, { grade = 3, system = {}, folder = null, sort = 0 } = {}) {
  const data = C.itemData(key, { grade, system });
  const _id = stableId(`item:${key}`);
  return { _id, _key: `!items!${_id}`, ...data, folder, sort, ownership: { default: 0 }, effects: [], flags: { flowstate: { catalogKey: key } }, _stats: STATS };
}
function folderDoc(name, sort) {
  const _id = stableId(`folder:${name}`);
  return { _id, _key: `!folders!${_id}`, name, type: "Item", folder: null, sorting: "a", sort, color: null, flags: {}, _stats: STATS };
}

const PACKS = {
  // The potions and the Festival Token (one generic token: the Adventure sets its roll per activity).
  consumables: () => [...Object.keys(POTIONS).map((k, i) => itemDoc(potionKey(k), { system: { quantity: 1 }, sort: i * 100 })),
    itemDoc(TOKEN_KEY, { system: { quantity: 1 }, sort: 1000 })],
  // Every Common catalog entry at Grade 3, foldered by type (Unarmed, Improvised and the plain Misc item are left out: everyone has them).
  "starting-gear": () => {
    const out = [];
    const folders = { weapon: "Weapons", armor: "Armor", foci: "Foci", shroud: "Shrouds", icon: "Icons", affix: "Affixes", ammo: "Ammunition" };
    const fid = {};
    Object.values(folders).forEach((name, i) => { const f = folderDoc(name, i * 100); fid[name] = f._id; out.push(f); });
    for (const [key, e] of Object.entries(C.ITEM_CATALOG)) {
      if (e.rarity !== "common" || e.hidden || !C.isGenerated(key)) continue;
      if (key === "weapon.unarmed" || key.startsWith("weapon.improvised") || key === "gear.misc" || key === TOKEN_KEY || key.startsWith("potion.")) continue;
      const kind = key.startsWith("ammo.") ? "ammo" : e.type;
      if (!folders[kind]) continue;
      out.push(itemDoc(key, { folder: fid[folders[kind]], system: kind === "ammo" ? { quantity: 20 } : {} }));
    }
    return out;
  }
};

const only = process.argv.slice(2);
const listed = [];
mkdirSync(join(root, "docs"), { recursive: true });
for (const [name, build] of Object.entries(PACKS)) {
  if (only.length && !only.includes(name)) continue;
  const docs = build();
  const src = join(here, "..", "packs", name), dest = join(root, "packs", name);
  rmSync(src, { recursive: true, force: true });
  mkdirSync(src, { recursive: true });
  for (const d of docs) writeFileSync(join(src, `${d._id}.json`), `${JSON.stringify(d, null, 2)}\n`);
  rmSync(dest, { recursive: true, force: true });
  await compilePack(src, dest, { log: false });
  console.log(`${name}: ${docs.length} documents → packs/${name}`);
  listed.push({ name, docs });
}
// The list of every pack document's UUID, for content that links to them (docs/PACK_IDS.md).
if (!only.length) {
  const lines = ["# Flow State compendium ids", "", "Generated by `npm run packs` (dev/tools/build-packs.mjs). Each id comes from the item's catalog key, so it stays the same across", "builds and system versions. Link to an item as `Compendium.flowstate.<pack>.Item.<id>` (the UUID column).", ""];
  for (const { name, docs } of listed) {
    lines.push(`## ${name}`, "", "| Item | Catalog key | UUID |", "| --- | --- | --- |");
    for (const d of docs.filter(x => x._key.startsWith("!items!"))) lines.push(`| ${d.name} | \`${d.flags.flowstate.catalogKey}\` | \`Compendium.flowstate.${name}.Item.${d._id}\` |`);
    lines.push("");
  }
  writeFileSync(join(root, "docs", "PACK_IDS.md"), lines.join("\n"));
}
